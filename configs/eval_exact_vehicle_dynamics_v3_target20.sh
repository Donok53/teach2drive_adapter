#!/usr/bin/env bash
set -euo pipefail

ADAPTER_ROOT=${ADAPTER_ROOT:-/home/byeongjae/code/teach2drive_adapter}
CARLA_ROOT=${CARLA_ROOT:-/home/byeongjae/carla-simulator}
GARAGE_ROOT=${GARAGE_ROOT:-/home/byeongjae/code/carla_garage}
TEAM_CONFIG=${TEAM_CONFIG:-/home/byeongjae/code/checkpoints/transfuserpp/pretrained_models/all_towns}
MISSION_DIR=${MISSION_DIR:-${ADAPTER_ROOT}/runs/leaderboard_tfpp_missions/routes_validation_01}
RUN_DIR=${RUN_DIR:?Set RUN_DIR to a new evaluation directory}
CHECKPOINT=${CHECKPOINT:?Set CHECKPOINT to the v3 vehicle dynamics best_model.pt}
GPU=${GPU:-1}
PORT=${PORT:-2043}
TM_PORT=${TM_PORT:-8043}
START_INDEX=${START_INDEX:-0}
LIMIT=${LIMIT:-20}
VIDEO_RECORD_INDICES=${VIDEO_RECORD_INDICES:-2,4}
MISSION_TIMEOUT_SEC=${MISSION_TIMEOUT_SEC:-500}
PYTHON_BIN_DIR=${PYTHON_BIN_DIR:-}

mkdir -p "${RUN_DIR}/traces"
if [[ -n "${PYTHON_BIN_DIR}" ]]; then
  export PATH="${PYTHON_BIN_DIR}:${PATH}"
fi

CUDA_VISIBLE_DEVICES="${GPU}" ADAPTER_ROOT="${ADAPTER_ROOT}" CARLA_ROOT="${CARLA_ROOT}" \
GARAGE_ROOT="${GARAGE_ROOT}" TEAM_CONFIG="${TEAM_CONFIG}" MISSION_DIR="${MISSION_DIR}" RUN_DIR="${RUN_DIR}" \
START_INDEX="${START_INDEX}" LIMIT="${LIMIT}" MAX_RESTARTS=30 FRESH_CARLA_ON_START=1 CARLA_WAIT_SEC=150 \
CARLA_QUALITY=Low CARLA_EXTRA_ARGS="${CARLA_EXTRA_ARGS:--graphicsadapter=${GPU}}" \
PORT="${PORT}" TM_PORT="${TM_PORT}" STOP_ON_TIMEOUT=0 STOP_ON_INVALID=0 INVALID_RETRY_LIMIT=2 DEBUG=1 \
RECORD_VIDEO="${RECORD_VIDEO:-1}" VIDEO_RECORD_INDICES="${VIDEO_RECORD_INDICES}" VIDEO_VIEW=topdown VIDEO_PIP_VIEW=front \
VIDEO_PIP_SCALE=0.30 VIDEO_NOTION_COMPAT=1 VIDEO_CODEC=mp4v VIDEO_WIDTH=1280 VIDEO_HEIGHT=720 VIDEO_FPS=20 \
TFPP_AGENT_RECORD_VIDEO=0 CLEANUP_AFTER_MISSION=1 EGO_VEHICLE_MODEL=vehicle.tesla.model3 \
AGENT_PATH="${ADAPTER_ROOT}/scripts/tfpp_vehicle_dynamics_v3_sensor_rig_agent.py" \
TFPP_SENSOR_RIG=tfpp_ego TFPP_SENSOR_CAMERA=front TFPP_SENSOR_LIDAR=top \
TFPP_VEHICLE_DYNAMICS_V3_CHECKPOINT="${CHECKPOINT}" \
TFPP_DYNAMICS_TRACE_PATH="${TFPP_DYNAMICS_TRACE_PATH:-${RUN_DIR}/traces/dynamics_v3.jsonl}" \
TFPP_DYNAMICS_BLEND="${TFPP_DYNAMICS_BLEND:-0.5}" TFPP_DYNAMICS_MAX_DELTA="${TFPP_DYNAMICS_MAX_DELTA:-0.12}" \
TFPP_DYNAMICS_TURN_THRESHOLD_YAW="${TFPP_DYNAMICS_TURN_THRESHOLD_YAW:-0.03}" \
TFPP_DYNAMICS_FULL_TURN_THRESHOLD_YAW="${TFPP_DYNAMICS_FULL_TURN_THRESHOLD_YAW:-0.12}" \
TFPP_DYNAMICS_CURVATURE_PROBE="${TFPP_DYNAMICS_CURVATURE_PROBE:-0.75}" \
TFPP_DYNAMICS_RISK_GATE_FLOOR="${TFPP_DYNAMICS_RISK_GATE_FLOOR:-0.25}" \
TFPP_DYNAMICS_MINIMUM_TARGET_SPEED="${TFPP_DYNAMICS_MINIMUM_TARGET_SPEED:-1.0}" \
TFPP_DYNAMICS_LAG1_FRAMES="${TFPP_DYNAMICS_LAG1_FRAMES:-5}" \
TFPP_DYNAMICS_LAG2_FRAMES="${TFPP_DYNAMICS_LAG2_FRAMES:-10}" \
MISSION_TIMEOUT_SEC="${MISSION_TIMEOUT_SEC}" \
bash "${ADAPTER_ROOT}/scripts/run_tfpp_mission_batch_autorestart.sh"
