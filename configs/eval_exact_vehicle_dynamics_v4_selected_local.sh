#!/usr/bin/env bash
set -euo pipefail

ADAPTER_ROOT=${ADAPTER_ROOT:-/home/byeongjae/code/teach2drive_adapter}
CARLA_ROOT=${CARLA_ROOT:-/home/byeongjae/carla-simulator}
GARAGE_ROOT=${GARAGE_ROOT:-/home/byeongjae/code/carla_garage}
TEAM_CONFIG=${TEAM_CONFIG:-/home/byeongjae/code/checkpoints/transfuserpp/pretrained_models/all_towns}
MISSION_DIR=${MISSION_DIR:-${ADAPTER_ROOT}/runs/leaderboard_tfpp_missions/routes_validation_01}
RUN_DIR=${RUN_DIR:-${ADAPTER_ROOT}/runs/eval_vehicle_dynamics_v4_b025_selected_20260814}
DYNAMICS_CHECKPOINT=${DYNAMICS_CHECKPOINT:-${ADAPTER_ROOT}/runs/remote_checkpoints/train_exact_vehicle_dynamics_v3_gpu0/best_model.pt}
CALIBRATOR_CHECKPOINT=${CALIBRATOR_CHECKPOINT:-${ADAPTER_ROOT}/runs/train_exact_vehicle_dynamics_v4_local/train/best_model.pt}
MISSION_LIST=${MISSION_LIST:-${RUN_DIR}/mission_routes.txt}
GPU=${GPU:-1}
PORT=${PORT:-2043}
TM_PORT=${TM_PORT:-8043}

mkdir -p "${RUN_DIR}/traces"
: > "${MISSION_LIST}"
for index in 2 4 5 8 11 15 17; do
  route=$(printf '%s/mission_%03d_' "${MISSION_DIR}" "${index}")
  match=$(compgen -G "${route}*.xml" | head -1)
  printf '%s\n' "${match}" >> "${MISSION_LIST}"
done

CUDA_VISIBLE_DEVICES="${GPU}" ADAPTER_ROOT="${ADAPTER_ROOT}" CARLA_ROOT="${CARLA_ROOT}" \
GARAGE_ROOT="${GARAGE_ROOT}" TEAM_CONFIG="${TEAM_CONFIG}" MISSION_DIR="${MISSION_DIR}" MISSION_LIST="${MISSION_LIST}" \
RUN_DIR="${RUN_DIR}" START_INDEX=0 LIMIT=7 MAX_RESTARTS=30 FRESH_CARLA_ON_START=1 CARLA_WAIT_SEC=150 \
CARLA_QUALITY=Low CARLA_EXTRA_ARGS="${CARLA_EXTRA_ARGS:--graphicsadapter=${GPU}}" PORT="${PORT}" TM_PORT="${TM_PORT}" \
STOP_ON_TIMEOUT=0 STOP_ON_INVALID=0 INVALID_RETRY_LIMIT=2 DEBUG=1 CLEANUP_AFTER_MISSION=1 \
RECORD_VIDEO=1 VIDEO_RECORD_INDICES=0,1,2,3,4 VIDEO_VIEW=topdown VIDEO_PIP_VIEW=front VIDEO_PIP_SCALE=0.30 \
VIDEO_NOTION_COMPAT=1 VIDEO_CODEC=mp4v VIDEO_WIDTH=1280 VIDEO_HEIGHT=720 VIDEO_FPS=20 TFPP_AGENT_RECORD_VIDEO=0 \
EGO_VEHICLE_MODEL=vehicle.tesla.model3 AGENT_PATH="${ADAPTER_ROOT}/scripts/tfpp_vehicle_dynamics_v4_sensor_rig_agent.py" \
TFPP_SENSOR_RIG=tfpp_ego TFPP_SENSOR_CAMERA=front TFPP_SENSOR_LIDAR=top \
TFPP_VEHICLE_DYNAMICS_V3_CHECKPOINT="${DYNAMICS_CHECKPOINT}" TFPP_YAW_HORIZON_V4_CHECKPOINT="${CALIBRATOR_CHECKPOINT}" \
TFPP_DYNAMICS_TRACE_PATH="${RUN_DIR}/traces/dynamics_v4.jsonl" TFPP_DYNAMICS_BLEND="${TFPP_DYNAMICS_BLEND:-0.25}" \
TFPP_DYNAMICS_MAX_DELTA=0.12 TFPP_DYNAMICS_TURN_THRESHOLD_YAW=0.03 TFPP_DYNAMICS_FULL_TURN_THRESHOLD_YAW=0.12 \
TFPP_DYNAMICS_PHASE_CURVATURE_SCALE=0.02 TFPP_DYNAMICS_EXIT_GATE_FLOOR=0.0 \
TFPP_DYNAMICS_OVERSHOOT_RATIO=0.95 TFPP_DYNAMICS_MINIMUM_TARGET_SPEED=2.0 \
TFPP_DYNAMICS_LAG1_FRAMES=5 TFPP_DYNAMICS_LAG2_FRAMES=10 MISSION_TIMEOUT_SEC=500 \
bash "${ADAPTER_ROOT}/scripts/run_tfpp_mission_batch_autorestart.sh"
