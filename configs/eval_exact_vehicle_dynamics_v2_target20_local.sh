DYNAMICS_CHECKPOINT=${DYNAMICS_CHECKPOINT:?Set DYNAMICS_CHECKPOINT}
CALIBRATOR_CHECKPOINT=${CALIBRATOR_CHECKPOINT:?Set CALIBRATOR_CHECKPOINT}
GPU=${GPU:-1}
